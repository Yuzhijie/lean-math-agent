import { describe, expect, it } from "vitest";
import { FIGURE_MARK, numbersIn, scopeNotes, statementScope, statementType } from "@/lib/lean/statement-scope";
import { problemWithFigure } from "@/lib/bank/problem-figures";

describe("statementType", () => {
  it("takes the type out of a statement, a whole verified source or a bare type", () => {
    expect(statementType("theorem t (x : ℝ) : x = x := by sorry")).toBe("(x : ℝ) : x = x");
    expect(statementType("-- Generated by lean-math-agent.\nimport Mathlib\n\ntheorem nat_add_zero : ∀ (n : ℕ), n + 0 = n := by\n  simp\n")).toBe(": ∀ (n : ℕ), n + 0 = n");
    expect(statementType(": 1 + 1 = 2")).toBe(": 1 + 1 = 2");
    // a let's `:=` is part of the statement; the proof's is not
    expect(statementType("theorem t : let f : ℕ → ℕ := fun n => n + 1;\n  f 2 = 3 := by\n  norm_num [show (7 : ℕ) = 7 from rfl]")).toBe(": let f : ℕ → ℕ := fun n => n + 1; f 2 = 3");
  });
});

describe("numbersIn", () => {
  it("reads numbers, not the digits of names or projections", () => {
    expect(numbersIn("AB=13，AC=14，BC=15")).toEqual([13, 14, 15]);
    expect(numbersIn("(h1 : x2 = 3.5) (A : ℝ × ℝ) : A.1 + A.2 = 28 / 3")).toEqual([3.5, 28, 3]);
    expect(numbersIn("x ^ 2 + y₁")).toEqual([2]);
  });
});

describe("statementScope", () => {
  const hyperbola = "求双曲线 $\\dfrac{x^2}{9}-\\dfrac{y^2}{16}=1$ 的右焦点到它的一条渐近线的距离。";

  it("a closed computation on numbers the problem does not give", () => {
    const s = statementScope(hyperbola, "theorem d : |4 * (5 : ℝ) - 3 * (0 : ℝ)| / Real.sqrt ((4 : ℝ)^2 + (-3 : ℝ)^2) = 4 := by sorry", ["4"]);
    expect(s).toEqual({ figure: false, closed: true, derived: ["5", "3"] });
    expect(scopeNotes(s).join(" ")).toMatch(/5、3|5, 3/);
    // lets with computed points are still a closed computation
    const lets = statementScope("在三角形 ABC 中，AB=13，AC=14，BC=15 … 求三角形 AED 的面积。", ": let A : ℝ × ℝ := (0, 0); let E : ℝ × ℝ := (6, 0); let D : ℝ × ℝ := (28 / 3, 56 / 9); |A.1 * (E.2 - D.2) + E.1 * (D.2 - A.2)| / 2 = 56 / 3", ["56/3"]);
    expect(lets.closed).toBe(true);
    expect(lets.derived).toEqual(["6", "28", "9"]);
  });

  it("the result a statement asserts is not a worked-out number, with or without a stored answer", () => {
    expect(statementScope("求 gcd(12, 18)", ": Nat.gcd 12 18 = 6").derived).toEqual([]);
    expect(statementScope("求 12 和 18 的最小公倍数与最大公因数之比", ": (Nat.lcm 12 18 : ℚ) / Nat.gcd 12 18 = 36 / 6").derived).toEqual([]);
    // a let's `:=`, `≠`, `≤` are not the result's `=`
    expect(statementScope("求 gcd(12, 18)", ": let d : ℕ := 7; Nat.gcd 12 18 ≠ d").derived).toEqual(["7"]);
  });

  it("the computation the problem asks for is not flagged", () => {
    expect(statementScope("求 2^2024+1 与 2^3036-1 的最大公因数。", ": Nat.gcd (2 ^ (2024 : ℕ) + 1) (2 ^ (3036 : ℕ) - 1) = 1", ["1"])).toEqual({ figure: false, closed: true, derived: [] });
    expect(scopeNotes(statementScope("计算 375 + 24 × 5 − 68", ": (375 : ℕ) + 24 * 5 - 68 = 427", ["427"]))).toEqual([]);
    // degrees written as radians
    expect(statementScope("求 cos 60° 的值", ": Real.cos (Real.pi / 3) = 1 / 2", ["1/2"]).derived).toEqual([]);
  });

  it("a statement with a variable is not a computation, whatever numbers it has", () => {
    const cases = [
      "(x y z : ℝ) (h1 : x + y + z = 4) : x ^ 4 + y ^ 4 + z ^ 4 = 98",
      ": IsLeast {n : ℕ | 0 < n ∧ 7^3 * 11^2 ∣ 3^n - 1} 1470",
      ": ∀ n : ℕ, 0 < n → 77 ∣ n → 7 ≤ n",
      ": (Finset.range 10).sum id = 45",
      ": let f : ℕ → ℕ := fun n => n + 17; f 2 = 19",
      ": (box : ℕ) → (1 ≤ box ∧ box ≤ 4) → box = 4",
    ];
    for (const type of cases) expect(statementScope("no numbers here", type), type).toMatchObject({ closed: false, derived: [] });
  });

  it("a problem that came with a figure, as lib/bank/problem-figures.ts appends it", () => {
    const problem = problemWithFigure("Jake used 4 of the vegetables for soup and served 3 with dinner. How many were not used?", "12 vegetables in a row");
    expect(FIGURE_MARK.test(problem)).toBe(true);
    const s = statementScope(problem, ": (12 : ℕ) - 4 - 3 = 5", ["5"]);
    expect(s.figure).toBe(true);
    expect(scopeNotes(s)).toHaveLength(1);
    expect(scopeNotes(s)[0]).toMatch(/带图|came with a figure/);
    expect(scopeNotes(statementScope("How many?", ": (x : ℕ) → x = x"))).toEqual([]);
  });
});
