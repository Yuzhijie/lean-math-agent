import { afterAll, beforeEach, describe, expect, it } from "vitest";
import path from "node:path";
import { hammer } from "@/lib/lean/hammer";
import { openTheorem } from "@/lib/lean/proof-state";
import { shutdownReplPool } from "@/lib/lean/repl";
import { resetLeanAvailability } from "@/lib/lean/sandbox";

// ProofSession in tactic mode against the fake REPL (fixtures/fake-repl.mjs); the real thing is
// tests/proof-state.integration.test.ts.
const FAKE = path.resolve(__dirname, "fixtures/fake-repl.mjs");
const SOURCE = "-- Generated by lean-math-agent. Do not edit lakefile.\nimport Mathlib\n\ntheorem t (n : Nat) : n + 0 = n := by\n  sorry";

beforeEach(() => {
  process.env.LEAN_REPL_COMMAND = `${process.execPath} ${FAKE}`;
  process.env.LEAN_SERVER_MODE = "server";
  resetLeanAvailability();
  shutdownReplPool();
});

afterAll(() => {
  shutdownReplPool();
  delete process.env.LEAN_REPL_COMMAND;
});

describe("ProofSession.apply (fake REPL)", () => {
  it("applies tactics to goal states", async () => {
    const { session, root } = (await openTheorem(SOURCE))!;
    try {
      const kept = await session.apply(root.state, "simp");
      expect(kept).toMatchObject({ ok: true, solved: false, goals: ["n : Nat\n⊢ n + 0 = n"] });
      const failed = await session.apply(root.state, "error_here");
      expect(failed).toMatchObject({ ok: false });
      const closed = await session.apply(root.state, "CLOSE");
      expect(closed).toMatchObject({ ok: true, solved: true, goals: [] });
    } finally {
      session.close();
    }
  });

  it("a tactic that kills the worker twice is a failed tactic, and the session goes on", async () => {
    const { session, root } = (await openTheorem(SOURCE))!;
    try {
      // `decide` over a million cases on a machine short of memory: the worker dies, is replaced, dies again
      const r = await session.apply(root.state, "BOOM");
      expect(r.ok).toBe(false);
      expect(r).toMatchObject({ error: expect.stringMatching(/died twice/) });
      // the next tactic runs on a fresh worker, from the same state
      expect(await session.apply(root.state, "CLOSE")).toMatchObject({ ok: true, solved: true });
    } finally {
      session.close();
    }
  });

  it("the hammer goes past such a tactic to the one that closes the goal", async () => {
    const { session, root } = (await openTheorem(SOURCE))!;
    try {
      const out = await hammer(session, root.state, { useMathlib: true, tactics: ["error_here", "BOOM", "CLOSE"] });
      expect(out.solved).toBe(true);
      expect(out.tactic).toBe("CLOSE");
      expect(out.attempts.map((a) => a.ok)).toEqual([false, false, true]);
      expect(out.attempts[1].error).toMatch(/died twice/);
    } finally {
      session.close();
    }
  });
});
