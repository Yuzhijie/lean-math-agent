/**
 * `npm run proofs:eval` — how useful the proof memory is (plan 7b P3 acceptance: more than 1000
 * proofs, similar-theorem hit rate). Writes bench/MEMORY.md.
 *
 *   --k n          recalled proofs per statement (default 2, as the prover gets)
 *   --threshold x  tactic overlap (Jaccard of tactic names) that counts as a hit (default 0.5)
 *   --replay       also replay the recalled proofs verbatim in Lean on every statement and count
 *                  how many Lean accepts (needs the Lean sandbox; no model calls)
 *   --limit n      replay on the first n statements only
 *
 * Leave-one-out: each stored proof's statement is used as a query against all the others, as if
 * that theorem were new.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { allProofs, recallScored } from "../lib/lean/proof-memory";
import { memoryHitStats } from "../lib/prover/dataset";
import { replayRecalled } from "../lib/prover/replay";
import { checkLeanAvailable } from "../lib/lean/sandbox";
import { shutdownReplPool } from "../lib/lean/repl";

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}
const flag = (name: string) => process.argv.includes(`--${name}`);
const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : "—");

async function main(): Promise<void> {
  for (const f of [".env.local", ".env"]) {
    try {
      process.loadEnvFile(path.resolve(f));
    } catch {
      // optional
    }
  }
  const k = Number(arg("k") ?? 2);
  const threshold = Number(arg("threshold") ?? 0.5);
  const entries = await allProofs();
  if (!entries.length) {
    console.error("the proof memory is empty — run npm run proofs:harvest -- bench/results/*.json first");
    process.exit(2);
  }
  const stats = await memoryHitStats(entries, { k, threshold });
  console.log(`memory: ${stats.entries} proofs; hit rate ${pct(stats.hits, stats.entries)} (top ${k}, tactic overlap ≥ ${threshold}); mean best overlap ${stats.meanBestJaccard.toFixed(2)}`);

  let replay: { tried: number; proved: number; checks: number } | undefined;
  if (flag("replay")) {
    const lean = await checkLeanAvailable();
    if (!lean.ok) {
      console.error(`--replay needs Lean: ${lean.message}`);
      process.exit(2);
    }
    const limit = arg("limit") !== undefined ? Number(arg("limit")) : entries.length;
    replay = { tried: 0, proved: 0, checks: 0 };
    for (const e of entries.slice(0, limit)) {
      const recalled = (await recallScored({ theoremType: e.theorem_type, problemText: e.problem_text, excludeType: e.theorem_type, k: 3, touch: false, among: entries })).map((r) => r.entry);
      replay.tried++;
      if (!recalled.length) continue;
      const r = await replayRecalled({ sessionId: `memory-eval-${e.id}`, theoremName: e.theorem_name, theoremType: e.theorem_type, recalled, useMathlib: true, opens: e.opens, count: false });
      if (r) {
        replay.proved++;
        replay.checks += r.tried;
      } else replay.checks += Math.min(3, recalled.length);
      if (replay.tried % 50 === 0) console.log(`  replay ${replay.tried}/${limit}: ${replay.proved} proved`);
    }
    console.log(`replay: ${replay.proved}/${replay.tried} statements proved by a recalled proof verbatim (${replay.checks} Lean checks)`);
    shutdownReplPool();
  }

  const md = [
    "# Proof memory",
    "",
    `Generated by \`npm run proofs:eval\` on ${new Date().toISOString().slice(0, 10)}. Leave-one-out: every stored proof's statement is a query against the other ${stats.entries - 1} proofs, as if it were a new theorem.`,
    "",
    "| Measure | Value |",
    "| --- | --- |",
    `| Proofs stored (target > 1000) | ${stats.entries} |`,
    `| Statements with a recalled neighbour | ${stats.withNeighbour} (${pct(stats.withNeighbour, stats.entries)}) |`,
    `| Hit rate: a top-${k} neighbour uses the same tactics (overlap ≥ ${threshold}) | ${stats.hits} (${pct(stats.hits, stats.entries)}) |`,
    `| Mean best tactic overlap | ${stats.meanBestJaccard.toFixed(2)} |`,
    ...(replay ? [`| Proved by replaying a recalled proof verbatim (Lean) | ${replay.proved} / ${replay.tried} (${pct(replay.proved, replay.tried)}), ${replay.checks} checks |`] : []),
    "",
    "| Source | Proofs | Hits |",
    "| --- | --- | --- |",
    ...Object.entries(stats.bySource)
      .sort((a, b) => b[1].entries - a[1].entries)
      .map(([src, s]) => `| ${src} | ${s.entries} | ${s.hits} (${pct(s.hits, s.entries)}) |`),
    "",
    "Grow the memory with `npm run proofs:harvest -- bench/results/*.json` (benchmark runs keep it read-only) and by solving; export it with `npm run proofs:export`.",
    "",
  ].join("\n");
  const out = arg("out") ?? "bench/MEMORY.md";
  await fs.mkdir(path.dirname(out), { recursive: true });
  await fs.writeFile(out, md);
  console.log(`wrote ${out}`);
}

if (process.argv[1] && /proofs-eval\.(ts|js|mts|mjs)$/.test(process.argv[1])) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
