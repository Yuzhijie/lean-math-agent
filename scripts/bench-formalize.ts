/**
 * Formalization benchmark (upgrade plan 7b, P1): how often does autoformalization turn a problem written
 * in words into the right Lean statement? The product's input is natural language, but until now only
 * proving was measured, from statements given in Lean.
 *
 * For a sample of miniF2F theorems, the informal statement goes through `autoformalize` (all its
 * validation layers) and the result is compared with the official Lean statement:
 *   - same:        both elaborate to the same signature (bound variables renamed)
 *   - equivalent:  the hammer proves `official ↔ ours`
 *   - not shown:   neither — unfaithful, or faithful in a form the hammer cannot connect
 *   - refuted:     our statement has a counterexample (miniF2F statements are true, so it is wrong)
 * plus how often the validation layers rejected the formalization, per layer, and the cost.
 *
 *   npm run bench:formalize -- [--sample 40] [--file bench/minif2f-test.json] [--concurrency 2] [--max-cost 3]
 *
 * Needs the LLM key and the Lean sandbox, like `npm run bench`. Spends real money (several model calls
 * per problem: formalization, back-translation, relevance check).
 */
import { promises as fs, existsSync } from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { autoformalize, canonicalSignature } from "../lib/llm/autoformalize";
import { assembleLeanSource } from "../lib/lean/assemble";
import { hammerTheorem } from "../lib/lean/hammer";
import { checkLeanAvailable, verifyLeanSource } from "../lib/lean/sandbox";
import { shutdownReplPool } from "../lib/lean/repl";
import { typeToProp } from "../lib/lean/statement-prop";
import { withUsageScope } from "../lib/llm/usage-tracker";
import { fixStatement } from "./fetch-benchmark";
import { sampleTheorems } from "./bench-ablation";
import { runPool } from "./bench";

export const LAYER_NAMES: Record<number, string> = {
  1: "elaborates",
  2: "not trivial",
  3: "back-translation",
  4: "numeric instances",
  5: "hypotheses relevant",
  6: "no counterexample",
};

export type Verdict = "same" | "equivalent" | "not_shown" | "refuted" | "not_formalized" | "official_broken";

export interface FormalizeRow {
  id: string;
  difficulty: string;
  accepted: boolean;
  verdict: Verdict;
  official: string;
  ours?: string;
  /** Layers that failed on the final attempt (numbers), and those that could not run. */
  failed_layers: number[];
  skipped_layers: number[];
  how?: string;
  cost?: number;
  wall_ms: number;
  error?: string;
}

const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "—");

export function renderFormalization(rows: FormalizeRow[], meta: { file: string; commit?: string; started_at: string }): string {
  const judged = rows.filter((r) => r.verdict !== "official_broken");
  const n = judged.length;
  const count = (v: Verdict) => judged.filter((r) => r.verdict === v).length;
  const faithful = count("same") + count("equivalent");
  const accepted = judged.filter((r) => r.accepted);
  const acceptedFaithful = accepted.filter((r) => r.verdict === "same" || r.verdict === "equivalent").length;
  const rejectedFaithful = judged.filter((r) => !r.accepted && (r.verdict === "same" || r.verdict === "equivalent")).length;
  const cost = rows.reduce((a, r) => a + (r.cost ?? 0), 0);
  const layerFails = new Map<number, number>();
  for (const r of judged) for (const l of r.failed_layers) layerFails.set(l, (layerFails.get(l) ?? 0) + 1);
  const out = [
    "# Formalization benchmark",
    "",
    `Generated by \`npm run bench:formalize\` on ${meta.started_at.slice(0, 10)}${meta.commit ? ` (${meta.commit})` : ""}: the informal miniF2F statements of ${n} theorems (${meta.file}) through autoformalization, compared with the official Lean statements.`,
    "",
    "| Result | Theorems | Share |",
    "| --- | --- | --- |",
    `| Same statement (signature) | ${count("same")} | ${pct(count("same"), n)} |`,
    `| Equivalent (hammer proved official ↔ ours) | ${count("equivalent")} | ${pct(count("equivalent"), n)} |`,
    `| **Faithful (same or equivalent)** | **${faithful}** | **${pct(faithful, n)}** |`,
    `| Not shown equivalent | ${count("not_shown")} | ${pct(count("not_shown"), n)} |`,
    `| Refuted (our statement is false) | ${count("refuted")} | ${pct(count("refuted"), n)} |`,
    `| No statement produced | ${count("not_formalized")} | ${pct(count("not_formalized"), n)} |`,
    "",
    `- Accepted by the validation layers: ${accepted.length}/${n} (${pct(accepted.length, n)}); of those, ${acceptedFaithful} shown faithful (${pct(acceptedFaithful, accepted.length)}).`,
    `- Rejected although shown faithful: ${rejectedFaithful} — the layers are too strict there.`,
    `- Accepted but not shown faithful: ${accepted.length - acceptedFaithful} — review these first (table below).`,
    `- Failed layers on the final attempt: ${[...layerFails].sort((a, b) => b[1] - a[1]).map(([l, k]) => `${l} ${LAYER_NAMES[l] ?? ""} ${k}`).join(", ") || "none"}.`,
    `- Cost ${`$${cost.toFixed(2)}`}, ${n ? `$${(cost / n).toFixed(3)}` : "—"} per problem.`,
    rows.length > n ? `- ${rows.length - n} official statement(s) did not elaborate and are left out.` : "",
    "",
  ].filter((l) => l !== "");
  const review = judged.filter((r) => r.accepted && r.verdict !== "same" && r.verdict !== "equivalent");
  if (review.length) {
    out.push("", "## Accepted but not shown faithful", "", "| Theorem | Verdict | Official | Ours |", "| --- | --- | --- | --- |");
    const cell = (s?: string) => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 160);
    for (const r of review) out.push(`| ${r.id} | ${r.verdict} | \`${cell(r.official)}\` | \`${cell(r.ours)}\` |`);
  }
  return out.join("\n") + "\n";
}

/** Compare two statements of one problem: same signature, or an equivalence the hammer proves. */
async function compare(id: string, official: string, ours: string, opens: string[] | undefined): Promise<{ verdict: "same" | "equivalent" | "not_shown"; how: string } | { broken: true }> {
  const sig = async (name: string, type: string, withOpens: boolean) =>
    (await verifyLeanSource(`formalize-${id}`, assembleLeanSource({ theoremName: name, theoremType: type, stepCodes: ["sorry"], useMathlib: true, opens: withOpens ? opens : undefined }), { allowSorry: true, theoremName: name, checkAxioms: false, wantSignature: true }));
  const a = await sig("official_stmt", official, true);
  if (!a.ok) return { broken: true };
  const b = await sig("our_stmt", ours, true);
  if (a.signature && b.signature && canonicalSignature(a.signature) === canonicalSignature(b.signature)) return { verdict: "same", how: "same signature" };
  const pa = typeToProp(official), pb = typeToProp(ours);
  if (!pa || !pb) return { verdict: "not_shown", how: "statement shape not understood" };
  const src = assembleLeanSource({ theoremName: "equiv_check", theoremType: `: (${pa}) ↔ (${pb})`, stepCodes: ["sorry"], useMathlib: true, opens });
  const hit = await hammerTheorem(src, { useMathlib: true });
  if (hit) {
    const v = await verifyLeanSource(`formalize-${id}`, assembleLeanSource({ theoremName: "equiv_check", theoremType: `: (${pa}) ↔ (${pb})`, stepCodes: [hit.tactic], useMathlib: true, opens }), { theoremName: "equiv_check" });
    if (v.ok) return { verdict: "equivalent", how: hit.tactic };
  }
  return { verdict: "not_shown", how: b.ok ? "hammer found no equivalence proof" : "our statement does not elaborate with the benchmark's opens" };
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

async function main(): Promise<void> {
  for (const f of [".env.local", ".env"]) {
    try {
      process.loadEnvFile(path.resolve(f));
    } catch {
      /* absent */
    }
  }
  const file = arg("file") ?? "bench/minif2f-test.json";
  if (!existsSync(file)) {
    console.error(`${file} not found — run npm run bench:fetch first`);
    process.exit(2);
  }
  const lean = await checkLeanAvailable();
  if (!lean.ok) {
    console.error(`Lean unavailable: ${lean.message}`);
    process.exit(2);
  }
  const parsed = JSON.parse(await fs.readFile(file, "utf8")) as { opens?: string[]; theorems: Array<{ id: string; difficulty?: string; name: string; type: string; informal?: string }> };
  const withText = parsed.theorems.filter((t) => t.informal?.trim());
  const theorems = sampleTheorems(withText, Number(arg("sample") ?? 40));
  const maxCost = Number(arg("max-cost") ?? 3);
  const concurrency = Math.max(1, Number(arg("concurrency") ?? 2));
  if (concurrency > 1 && !process.env.LEAN_REPL_WORKERS) process.env.LEAN_REPL_WORKERS = String(Math.min(concurrency, 8));
  const started = new Date();
  let spent = 0;
  console.log(`formalize: ${theorems.length} informal statements from ${path.basename(file)}, cost cap $${maxCost}`);
  const rows = (
    await runPool(theorems, concurrency, async (t): Promise<FormalizeRow | undefined> => {
      if (spent >= maxCost) return undefined;
      const t0 = Date.now();
      const official = fixStatement(t.type);
      const row = await withUsageScope(async (metrics): Promise<FormalizeRow> => {
        const base = { id: t.id, difficulty: t.difficulty ?? "?", official, failed_layers: [] as number[], skipped_layers: [] as number[] };
        try {
          const r = await autoformalize({ problemText: t.informal! });
          const failed = r.validation_results.filter((v) => !v.pass).map((v) => v.layer);
          const skipped = r.validation_results.filter((v) => v.skipped).map((v) => v.layer);
          const ours = r.theorem_type;
          const refuted = r.refutation?.verdict === "refuted";
          if (!ours || failed.includes(1)) return { ...base, accepted: r.accepted, verdict: "not_formalized", ours, failed_layers: failed, skipped_layers: skipped, cost: metrics().estimated_cost, wall_ms: Date.now() - t0 };
          const c = await compare(t.id, official, ours, parsed.opens);
          if ("broken" in c) return { ...base, accepted: r.accepted, verdict: "official_broken", ours, failed_layers: failed, skipped_layers: skipped, cost: metrics().estimated_cost, wall_ms: Date.now() - t0 };
          const verdict: Verdict = refuted && c.verdict === "not_shown" ? "refuted" : c.verdict;
          return { ...base, accepted: r.accepted, verdict, ours, how: c.how, failed_layers: failed, skipped_layers: skipped, cost: metrics().estimated_cost, wall_ms: Date.now() - t0 };
        } catch (e) {
          return { ...base, accepted: false, verdict: "not_formalized", error: (e instanceof Error ? e.message : String(e)).slice(0, 200), cost: metrics().estimated_cost, wall_ms: Date.now() - t0 };
        }
      });
      spent += row.cost ?? 0;
      console.log(`${row.verdict.padEnd(15)} ${row.accepted ? "accepted" : "rejected"}  ${row.id.padEnd(30)} ${(row.wall_ms / 1000).toFixed(0)}s${row.cost !== undefined ? ` $${row.cost.toFixed(3)}` : ""}${row.failed_layers.length ? `  failed layers ${row.failed_layers.join(",")}` : ""}${row.error ? `  ${row.error.slice(0, 80)}` : ""}`);
      return row;
    })
  ).filter((r): r is FormalizeRow => !!r);
  let commit: string | undefined;
  try {
    commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    /* not a repo */
  }
  const stamp = started.toISOString().replace(/[:.]/g, "-");
  await fs.mkdir("bench/results", { recursive: true });
  const out = `bench/results/${stamp}-formalize.json`;
  await fs.writeFile(out, JSON.stringify({ started_at: started.toISOString(), file: path.basename(file), commit, model: process.env.LLM_MODEL, rows }, null, 2));
  await fs.writeFile("bench/FORMALIZATION.md", renderFormalization(rows, { file: path.basename(file), commit, started_at: started.toISOString() }));
  console.log(`\nresults → ${out}\nreport  → bench/FORMALIZATION.md`);
  shutdownReplPool();
}

if (process.argv[1] && /bench-formalize\.(ts|js|mts|mjs)$/.test(process.argv[1])) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
