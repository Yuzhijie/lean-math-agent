/**
 * Benchmark report: turns one or more `npm run bench` result files into Markdown
 * (bench/BASELINE.md) — one summary row per run, then per run the stages that proved
 * theorems, the failure buckets and cost, and for runs over the same theorems what changed.
 *
 *   npm run bench:report -- bench/results/a.json bench/results/b.json [--out bench/BASELINE.md] [--title "…"]
 */
import { promises as fs } from "node:fs";
import path from "node:path";

export interface ResultRow {
  id: string;
  difficulty: string;
  ok: boolean;
  proved_by: string;
  wall_ms: number;
  llm_calls?: number;
  tokens?: number;
  cost?: number;
  failure?: { kind: string; detail: string };
  skipped?: boolean;
  /** Second attempt after an environment failure (bench retries those once). */
  retried?: boolean;
  /** Replaced by a later re-run (bench:merge). */
  rerun?: boolean;
}

export interface ResultFile {
  started_at: string;
  elapsed_ms?: number;
  file: string;
  strategy: string;
  budget: string;
  concurrency?: number;
  memory?: string;
  max_cost?: number;
  commit?: string;
  model?: string;
  prover_model?: string;
  pass: number;
  total: number;
  skipped?: string[];
  rows: ResultRow[];
  /** Set by bench:merge — re-runs folded into this run. */
  merged_reruns?: { started_at: string; commit?: string; theorems: number }[];
}

export interface NamedResult {
  name: string;
  result: ResultFile;
}

const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(0)}%` : "—");
const usd = (n: number) => `$${n.toFixed(2)}`;
const mins = (ms: number) => (ms >= 3_600_000 ? `${(ms / 3_600_000).toFixed(1)} h` : `${(ms / 60_000).toFixed(1)} min`);
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function count(items: string[]): [string, number][] {
  const m = new Map<string, number>();
  for (const k of items) m.set(k, (m.get(k) ?? 0) + 1);
  return [...m].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

function stats(r: ResultFile) {
  const ran = r.rows.filter((x) => !x.skipped);
  const passed = ran.filter((x) => x.ok);
  const failed = ran.filter((x) => !x.ok);
  const cost = ran.reduce((a, x) => a + (x.cost ?? 0), 0);
  const failCost = failed.reduce((a, x) => a + (x.cost ?? 0), 0);
  const sumMs = ran.reduce((a, x) => a + x.wall_ms, 0);
  const byDifficulty = ["easy", "medium", "hard"]
    .map((d) => {
      const rs = ran.filter((x) => x.difficulty === d);
      return rs.length ? `${d} ${rs.filter((x) => x.ok).length}/${rs.length}` : "";
    })
    .filter(Boolean)
    .join(", ");
  return { ran, passed, failed, cost, failCost, sumMs, byDifficulty, elapsed: r.elapsed_ms ?? sumMs };
}

/** Markdown for a set of runs (oldest first). */
export function renderReport(runs: NamedResult[], title = "Prover benchmark baseline"): string {
  const out: string[] = [`# ${title}`, ""];
  out.push(
    "Generated by `npm run bench:report` from the result files below. Statements are given in Lean, so autoformalization is not measured. " +
      "Cost is estimated from `LLM_PRICES`.",
    "",
  );
  out.push("| Run | Date | File | Strategy / budget | Passed | By difficulty | Cost | Cost per proof | Elapsed | Commit |");
  out.push("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const { name, result: r } of runs) {
    const s = stats(r);
    out.push(
      `| ${cell(name)} | ${r.started_at.slice(0, 10)} | ${cell(r.file)} | ${r.strategy} / ${r.budget}${r.concurrency && r.concurrency > 1 ? ` ×${r.concurrency}` : ""} | ` +
        `${s.passed.length}/${s.ran.length} (${pct(s.passed.length, s.ran.length)})${r.skipped?.length ? `, ${r.skipped.length} not run` : ""} | ${s.byDifficulty || "—"} | ` +
        `${usd(s.cost)} | ${s.passed.length ? usd(s.cost / s.passed.length) : "—"} | ${mins(s.elapsed)} | ${r.commit ?? "—"} |`,
    );
  }
  out.push("");

  for (const { name, result: r } of runs) {
    const s = stats(r);
    out.push(`## ${name}`, "");
    const model = [r.model && `model ${r.model}`, r.prover_model && `prover ${r.prover_model}`, r.memory && `memory ${r.memory}`, r.max_cost !== undefined && `cost cap $${r.max_cost}`]
      .filter(Boolean)
      .join(" · ");
    if (model) out.push(model, "");
    out.push(
      `- Proved by: ${count(s.passed.map((x) => x.proved_by)).map(([k, n]) => `${k} ${n}`).join(", ") || "—"}`,
      `- Failures: ${count(s.failed.map((x) => x.failure?.kind ?? "other")).map(([k, n]) => `${k} ${n}`).join(", ") || "—"}`,
      `- Failed theorems took ${usd(s.failCost)} of ${usd(s.cost)} (${pct(s.failCost, s.cost)}) and ${mins(s.failed.reduce((a, x) => a + x.wall_ms, 0))} of ${mins(s.sumMs)} theorem time; ` +
        `a proved theorem took ${s.passed.length ? (s.passed.reduce((a, x) => a + x.wall_ms, 0) / s.passed.length / 1000).toFixed(0) : "—"} s on average.`,
    );
    if (r.skipped?.length) out.push(`- Not run (cost cap): ${r.skipped.length} theorem(s).`);
    const retried = s.ran.filter((x) => x.retried).length;
    if (retried) out.push(`- Retried once after an environment failure (model unreachable or a hung Lean worker): ${retried} theorem(s).`);
    if (r.merged_reruns?.length) {
      const n = s.ran.filter((x) => x.rerun).length;
      out.push(`- Includes a re-run of ${n} theorem(s) after fixes (${r.merged_reruns.map((m) => `${m.started_at.slice(0, 10)}${m.commit ? ` @ ${m.commit}` : ""}`).join(", ")}); failure buckets re-classified with the current rules.`);
    }
    out.push("");
  }

  // Runs over the same theorems: what changed between consecutive ones.
  for (let i = 1; i < runs.length; i++) {
    const prev = runs[i - 1];
    const cur = runs[i];
    const before = new Map(prev.result.rows.filter((x) => !x.skipped).map((x) => [x.id, x]));
    const common = cur.result.rows.filter((x) => !x.skipped && before.has(x.id));
    if (!common.length) continue;
    const gained = common.filter((x) => x.ok && !before.get(x.id)!.ok);
    const lost = common.filter((x) => !x.ok && before.get(x.id)!.ok);
    const okBefore = common.filter((x) => before.get(x.id)!.ok).length;
    const okNow = common.filter((x) => x.ok).length;
    out.push(`## ${cur.name} vs ${prev.name}`, "");
    out.push(`On the ${common.length} theorems both runs attempted: ${okBefore} → ${okNow} proved.`, "");
    if (gained.length || lost.length) {
      out.push("| Theorem | Difficulty | Before | Now |", "| --- | --- | --- | --- |");
      for (const x of [...gained, ...lost]) {
        const b = before.get(x.id)!;
        const show = (y: ResultRow) => (y.ok ? `proved (${y.proved_by})` : `failed (${y.failure?.kind ?? "other"})`);
        out.push(`| ${cell(x.id)} | ${x.difficulty} | ${show(b)} | ${show(x)} |`);
      }
      out.push("");
    }
  }
  return out.join("\n").trimEnd() + "\n";
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

async function main(): Promise<void> {
  const files: string[] = [];
  for (let i = 2; i < process.argv.length; i++) {
    if (process.argv[i].startsWith("--")) {
      i++;
      continue;
    }
    files.push(process.argv[i]);
  }
  if (!files.length) {
    console.error("usage: npm run bench:report -- <result.json>… [--out bench/BASELINE.md] [--title …]");
    process.exit(2);
  }
  const runs: NamedResult[] = [];
  for (const f of files) {
    const result = JSON.parse(await fs.readFile(f, "utf8")) as ResultFile;
    const label = (
      arg(`name-${runs.length + 1}`) ??
      `${result.file.replace(/\.json$/, "")} ${result.total} · ${result.budget} · ${result.started_at.slice(0, 10)}${result.merged_reruns?.length ? " + re-run" : ""}`
    ).trim();
    runs.push({ name: label, result });
  }
  runs.sort((a, b) => a.result.started_at.localeCompare(b.result.started_at));
  const md = renderReport(runs, arg("title"));
  const outPath = arg("out");
  if (outPath) {
    await fs.mkdir(path.dirname(outPath), { recursive: true });
    await fs.writeFile(outPath, md, "utf8");
    console.log(`report → ${outPath}`);
  } else {
    process.stdout.write(md);
  }
}

if (process.argv[1] && /bench-report\.(ts|js|mts|mjs)$/.test(process.argv[1])) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
