/**
 * Ablations (upgrade plan 7b, P1): what each part of the prover is worth, in theorems and dollars.
 * Runs the benchmark once per variant on the same fixed sample of miniF2F theorems and writes
 * bench/ABLATION.md: proved, cost, cost per proof, theorems gained/lost against the base run, and the
 * marginal theorems per dollar of each change.
 *
 *   npm run bench:ablation -- [--variants base,no_retrieval,whole_proof,early_stop,sketch,normal]
 *                             [--sample 60] [--concurrency 3] [--max-cost 3] [--file bench/minif2f-test.json]
 *   npm run bench:ablation -- --report bench/results/<stamp>-ablation-*.json   (only rewrite the table)
 *
 * Variants (all on the low budget unless named otherwise):
 *   base          cascade: hammer → whole proof (the configuration of the 192/244 baseline)
 *   no_retrieval  base without premise retrieval / proof memory in the prompts
 *   seed_premises base retrieving from the curated seed lemmas only (ignores a built index): with
 *                 the full index built (npm run premises:build), base − seed_premises is its value
 *   whole_proof   whole proof only, no hammer
 *   early_stop    base + give up after round 0 when no sample got past its first tactic
 *   sketch        base + sketch-and-fill after the whole proof (SKETCH_ENABLED=true)
 *   normal        cascade on the normal budget (4 samples, 2 repair rounds, sketch)
 *   cost_cap      base + $0.02 per-theorem cost cap
 *
 * The sample is deterministic: theorems sorted by id, every k-th one per difficulty, so runs on
 * different days compare the same theorems. Spends real money: about $0.5 per low-budget variant on
 * 60 theorems at the 2026-10 prices; --max-cost caps each variant.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

export const VARIANTS: Record<string, { args: string[]; env?: Record<string, string>; note: string }> = {
  base: { args: ["--budget", "low"], note: "cascade, low budget" },
  no_retrieval: { args: ["--budget", "low", "--no-retrieval"], note: "no premise retrieval" },
  seed_premises: { args: ["--budget", "low"], env: { PREMISE_INDEX_PATH: ".data/no-premise-index.json" }, note: "retrieval from the ~700 seed lemmas only" },
  whole_proof: { args: ["--budget", "low", "--strategy", "whole_proof"], note: "no hammer" },
  early_stop: { args: ["--budget", "low", "--early-stop"], note: "give up when round 0 made no progress" },
  sketch: { args: ["--budget", "low"], env: { SKETCH_ENABLED: "true" }, note: "sketch-and-fill on" },
  normal: { args: ["--budget", "normal"], note: "normal budget" },
  cost_cap: { args: ["--budget", "low", "--cost-cap", "0.02"], note: "$0.02 per theorem" },
};

interface Row {
  id: string;
  difficulty: string;
  ok: boolean;
  proved_by: string;
  cost?: number;
  wall_ms: number;
  skipped?: boolean;
}
interface Result {
  rows: Row[];
  started_at: string;
  ablation?: string;
}

/** Every k-th theorem of each difficulty (sorted by id), about `n` in all. */
export function sampleTheorems<T extends { id: string; difficulty?: string }>(all: T[], n: number): T[] {
  if (n >= all.length) return [...all];
  const groups = new Map<string, T[]>();
  for (const t of [...all].sort((a, b) => a.id.localeCompare(b.id))) groups.set(t.difficulty ?? "?", [...(groups.get(t.difficulty ?? "?") ?? []), t]);
  const out: T[] = [];
  for (const g of groups.values()) {
    const want = Math.max(1, Math.round((n * g.length) / all.length));
    const step = g.length / want;
    for (let i = 0; i < want; i++) out.push(g[Math.floor(i * step)]);
  }
  return out;
}

const usd = (n: number) => `$${n.toFixed(2)}`;

/** Markdown table: one row per variant against the first (base) one. */
export function renderAblation(runs: Array<{ name: string; result: Result }>): string {
  const stat = (r: Result) => {
    const ran = r.rows.filter((x) => !x.skipped);
    const proved = ran.filter((x) => x.ok);
    const cost = ran.reduce((a, x) => a + (x.cost ?? 0), 0);
    const ms = ran.reduce((a, x) => a + x.wall_ms, 0);
    return { ran, proved, cost, ms, ids: new Set(proved.map((x) => x.id)) };
  };
  const base = runs[0];
  const b = stat(base.result);
  const out = [
    "# Ablations",
    "",
    `Generated by \`npm run bench:ablation\`. Same ${b.ran.length} miniF2F theorems for every variant; "${base.name}" is the reference. ` +
      "Marginal = extra theorems proved per extra dollar against the reference (negative cost: money saved).",
    "",
    "| Variant | What changes | Proved | Cost | Per proof | Theorem time | vs reference | Marginal |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const { name, result } of runs) {
    const s = stat(result);
    const gained = [...s.ids].filter((id) => !b.ids.has(id)).length;
    const lost = [...b.ids].filter((id) => !s.ids.has(id)).length;
    const dProved = s.proved.length - b.proved.length;
    const dCost = s.cost - b.cost;
    const marginal =
      name === base.name ? "—" : Math.abs(dCost) < 0.005 ? (dProved ? `${dProved > 0 ? "+" : ""}${dProved} at no cost` : "no change") : `${(dProved / dCost).toFixed(1)} per $ (${dProved >= 0 ? "+" : ""}${dProved} for ${dCost >= 0 ? "+" : "−"}${usd(Math.abs(dCost))})`;
    out.push(
      `| ${name} | ${VARIANTS[name]?.note ?? result.ablation ?? ""} | ${s.proved.length}/${s.ran.length} | ${usd(s.cost)} | ${s.proved.length ? usd(s.cost / s.proved.length) : "—"} | ${(s.ms / 60000).toFixed(1)} min | ` +
        `${name === base.name ? "—" : `+${gained} / −${lost}`} | ${marginal} |`,
    );
  }
  out.push("");
  const hammer = b.proved.filter((x) => x.proved_by === "hammer").length;
  if (hammer) out.push(`In the reference run the hammer proved ${hammer} of ${b.proved.length} theorems without any model call.`, "");
  return out.join("\n");
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function main(): void {
  const RESULTS = "bench/results";
  const reportOnly = process.argv.includes("--report");
  if (reportOnly) {
    const files = process.argv.slice(process.argv.indexOf("--report") + 1).filter((a) => !a.startsWith("--"));
    const runs = files.map((f) => {
      const result = JSON.parse(readFileSync(f, "utf8")) as Result;
      return { name: result.ablation ?? path.basename(f, ".json"), result };
    });
    runs.sort((a, b) => (a.name === "base" ? -1 : b.name === "base" ? 1 : 0));
    writeFileSync("bench/ABLATION.md", renderAblation(runs));
    console.log("report → bench/ABLATION.md");
    return;
  }
  const file = arg("file") ?? "bench/minif2f-test.json";
  if (!existsSync(file)) {
    console.error(`${file} not found — run npm run bench:fetch first`);
    process.exit(2);
  }
  const names = (arg("variants") ?? "base,no_retrieval,whole_proof,early_stop,sketch").split(",").map((s) => s.trim()).filter(Boolean);
  const unknown = names.filter((n) => !VARIANTS[n]);
  if (unknown.length) {
    console.error(`unknown variant(s): ${unknown.join(", ")}; known: ${Object.keys(VARIANTS).join(", ")}`);
    process.exit(2);
  }
  // The reference run always comes first.
  const ordered = ["base", ...names.filter((n) => n !== "base")];
  const index = process.env.PREMISE_INDEX_PATH ?? ".data/premise-index.json";
  console.log(existsSync(index) ? `Premise index: ${index}` : `No premise index at ${index}: retrieval uses the seed lemmas (npm run premises:build to build one)`);
  const parsed = JSON.parse(readFileSync(file, "utf8")) as { theorems?: Array<{ id: string; difficulty?: string }> } | Array<{ id: string; difficulty?: string }>;
  const all = Array.isArray(parsed) ? parsed : parsed.theorems ?? [];
  const ids = sampleTheorems(all, Number(arg("sample") ?? 60)).map((t) => t.id);
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  mkdirSync(RESULTS, { recursive: true });
  console.log(`Ablation on ${ids.length} theorems: ${ordered.join(", ")}`);
  const runs: Array<{ name: string; result: Result }> = [];
  for (const name of ordered) {
    const v = VARIANTS[name];
    const out = path.join(RESULTS, `${stamp}-ablation-${name}.json`);
    const cmd = [process.execPath, path.join("node_modules", "tsx", "dist", "cli.mjs"), "scripts/bench.ts", "--file", file, "--only", ids.join(","), "--concurrency", arg("concurrency") ?? "3", "--max-cost", arg("max-cost") ?? "3", "--json", out, ...v.args];
    const [bin, ...rest] = process.platform === "darwin" && existsSync("/usr/bin/caffeinate") ? ["/usr/bin/caffeinate", "-i", ...cmd] : cmd;
    console.log(`\n=== ${name} (${v.note}) ===`);
    const r = spawnSync(bin, rest, { stdio: "inherit", env: { ...process.env, ...(v.env ?? {}) } });
    if (r.status !== 0) {
      console.error(`${name} failed (exit ${r.status ?? r.signal}); continuing with the others`);
      continue;
    }
    const result = JSON.parse(readFileSync(out, "utf8")) as Result;
    result.ablation = name;
    writeFileSync(out, JSON.stringify(result, null, 2));
    runs.push({ name, result });
  }
  if (!runs.length) process.exit(1);
  writeFileSync("bench/ABLATION.md", renderAblation(runs));
  console.log("\nreport → bench/ABLATION.md");
}

if (process.argv[1] && /bench-ablation\.(ts|js|mts|mjs)$/.test(process.argv[1])) main();
