import type { ProofStep, SorryLabel } from "../types";

export const LEAN_HEADER = `-- Generated by lean-math-agent. Do not edit lakefile.
`;

/** Default imports when Mathlib mode is enabled. */
export const MATHLIB_IMPORTS = ["Mathlib", "Batteries", "Aesop"];

export function stepCodesUpTo(steps: ProofStep[], stepIndex: number): string[] {
  return steps
    .filter((s) => s.index <= stepIndex)
    .sort((a, b) => a.index - b.index)
    .map((s) => s.lean_code)
    .filter(Boolean);
}

export function assembleLeanSource(opts: {
  theoremName: string;
  theoremType: string;
  stepCodes: string[];
  /** Append trailing `sorry` for incomplete prefixes during step repair verifies. */
  appendSorry?: boolean;
  /** Lean module imports (e.g., ["Mathlib"]). Inserted after header.
   *  When `useMathlib` is true and no explicit imports are given, uses MATHLIB_IMPORTS. */
  imports?: string[];
  /** When true, auto-include Mathlib + Batteries + Aesop imports. */
  useMathlib?: boolean;
  /** Sorry annotations as comments before each sorry step. */
  sorryLabels?: SorryLabel[];
  /** Namespaces to open for the declaration (`open A B in` right before `theorem`). */
  opens?: string[];
}): string {
  // Resolve imports: explicit > useMathlib default > none
  const resolvedImports =
    opts.imports && opts.imports.length > 0
      ? opts.imports
      : opts.useMathlib
        ? MATHLIB_IMPORTS
        : undefined;

  // Build imports section
  const importLines =
    resolvedImports && resolvedImports.length > 0
      ? resolvedImports.map((m) => `import ${m}`).join("\n") + "\n\n"
      : "";

  // Build step body with optional sorry annotations
  const parts: string[] = [];
  for (const code of opts.stepCodes) {
    const trimmed = code.trim();
    if (!trimmed) continue;

    // Check if this step has a sorry annotation
    const label = opts.sorryLabels?.find(
      (l) => trimmed.includes("sorry") && l.step_index >= 0,
    );
    if (label) {
      parts.push(`-- SORRY: Step ${label.step_index} — ${label.reason}`);
    }
    parts.push(trimmed);
  }

  if (opts.appendSorry) {
    parts.push("sorry");
  }
  const body = parts.join("\n\n");
  // Final verify must never silently succeed via empty/`sorry` body.
  // Use `fail` so lake rejects empty assemblies; repair path uses appendSorry.
  const tacticBody = body || (opts.appendSorry ? "sorry" : "fail");
  const openLine = opts.opens && opts.opens.length > 0 ? `open ${opts.opens.join(" ")} in\n` : "";
  return `${LEAN_HEADER}${importLines}${openLine}theorem ${opts.theoremName} ${opts.theoremType} := by
${indent(tacticBody)}
`;
}

function indent(s: string): string {
  return s
    .split("\n")
    .map((line) => (line.length ? `  ${line}` : line))
    .join("\n");
}
